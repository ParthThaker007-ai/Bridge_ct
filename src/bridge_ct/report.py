"""Grounded evidence reports. Every statement is derived from source records and carries its identifier.

No text is generated by a language model; when source records are missing the report ABSTAINS instead of guessing.
"""
from __future__ import annotations

from typing import Any, Dict, List

import pandas as pd

DISCLAIMER = ("Structurally disconnected candidate pair identified from public bibliographic data. "
              "This is a research-analysis output, not clinical decision support, and does not show that a "
              "collaboration would cause any medical benefit.")


class EvidenceReporter:
    """Looks up supporting records for a candidate pair.

    Parameters: ``tables`` (canonical tables), ``pair_table`` (for shared collaborators), ``links`` (paper->trial).
    """

    def __init__(self, tables: Dict[str, Any], pair_table: pd.DataFrame) -> None:
        self.works = tables["works"].set_index("work_id")
        self.ships = tables["authorships"][["work_id", "author_id", "publication_year"]]
        self.names = dict(zip(tables["authors"]["author_id"], tables["authors"]["display_name"]))
        self.topics = dict(zip(tables["topics"]["topic_id"], tables["topics"]["label"]))
        self.work_topics = tables["work_topics"]
        self.links = tables.get("paper_trial_links", pd.DataFrame())
        self.trials = tables.get("trials", pd.DataFrame()).set_index("nct_id") if len(tables.get("trials", [])) else pd.DataFrame()
        self.pair_table = pair_table

    def _author_works(self, author: str, cutoff: int, n: int) -> pd.DataFrame:
        ids = self.ships[(self.ships["author_id"] == author) & (self.ships["publication_year"] <= cutoff)]["work_id"]
        w = self.works.loc[self.works.index.intersection(ids)]
        return w.sort_values(["publication_year", "title"], ascending=[False, True]).head(n)

    def report(self, row: pd.Series, top_works: int = 5) -> Dict[str, Any]:
        """Evidence dictionary for one shortlist row (needs ``u, v, cutoff``; other columns are echoed)."""
        u, v, t = row["u"], row["v"], int(row["cutoff"])
        wu, wv = self._author_works(u, t, top_works), self._author_works(v, t, top_works)
        rep: Dict[str, Any] = {
            "pair": [{"author_id": a, "name": self.names.get(a, "")} for a in (u, v)], "cutoff_year": t,
            "probability": float(row.get("prob", float("nan"))), "prob_lo": float(row.get("prob_lo", float("nan"))),
            "prob_hi": float(row.get("prob_hi", float("nan"))), "rank": int(row.get("rank", 0)),
            "communities": [int(row.get("comm_u", -1)), int(row.get("comm_v", -1))],
            "top_feature_contributions": row.get("top_contributions", ""), "disclaimer": DISCLAIMER}
        if wu.empty or wv.empty:
            rep["status"] = "abstain: no source records for at least one author before the cutoff"
            return rep
        rep["status"] = "ok"
        fmt = lambda w: [{"work_id": i, "year": int(r.publication_year), "title": r.title,
                          "url": f"https://openalex.org/{i}", "doi": r.doi} for i, r in w.iterrows()]
        rep["supporting_works"] = {u: fmt(wu), v: fmt(wv)}
        ids = list(wu.index) + list(wv.index)
        wt = self.work_topics[self.work_topics["work_id"].isin(ids)]
        by = {a: set(wt[wt["work_id"].isin(w.index)]["topic_id"]) for a, w in ((u, wu), (v, wv))}
        shared = by[u] & by[v]
        rep["shared_topics"] = sorted(self.topics.get(t_, t_) for t_ in shared)[:10]
        cu = set(self.pair_table[(self.pair_table["year"] <= t) & (self.pair_table["u"] == u)]["v"]) | \
             set(self.pair_table[(self.pair_table["year"] <= t) & (self.pair_table["v"] == u)]["u"])
        cv = set(self.pair_table[(self.pair_table["year"] <= t) & (self.pair_table["u"] == v)]["v"]) | \
             set(self.pair_table[(self.pair_table["year"] <= t) & (self.pair_table["v"] == v)]["u"])
        rep["shared_collaborators"] = [{"author_id": a, "name": self.names.get(a, "")} for a in sorted(cu & cv)[:10]]
        trial_ev: List[Dict[str, Any]] = []
        if len(self.links):
            lk = self.links[self.links["work_id"].isin(ids)]
            for r in lk.itertuples(index=False):
                reg = self.trials.loc[r.nct_id, "registration_year"] if len(self.trials) and r.nct_id in self.trials.index else None
                if reg is not None and int(reg) <= t:
                    trial_ev.append({"nct_id": r.nct_id, "work_id": r.work_id, "method": r.method,
                                     "confidence": float(r.confidence), "evidence_uri": r.evidence_uri,
                                     "registration_year": int(reg), "reviewed": bool(r.reviewed)})
        rep["trial_evidence"] = trial_ev
        return rep


def to_markdown(rep: Dict[str, Any]) -> str:
    """Human-readable rendering of :meth:`EvidenceReporter.report`."""
    a, b = rep["pair"]
    lines = [f"# Candidate bridge: {a['name'] or a['author_id']} <-> {b['name'] or b['author_id']}",
             f"*Cutoff year:* {rep['cutoff_year']} | *rank:* {rep['rank']} | "
             f"*P(new collaboration within horizon):* {rep['probability']:.3f} "
             f"(90% credible interval {rep['prob_lo']:.3f}-{rep['prob_hi']:.3f})", "",
             f"> {rep['disclaimer']}", ""]
    if rep["status"] != "ok":
        return "\n".join(lines + [f"**Status:** {rep['status']}"])
    lines.append(f"**Top feature contributions (logit scale):** {rep['top_feature_contributions']}")
    lines.append(f"**Shared topics:** {', '.join(rep['shared_topics']) or 'none found'}")
    lines.append(f"**Shared collaborators:** {', '.join(c['name'] or c['author_id'] for c in rep['shared_collaborators']) or 'none'}")
    for aid, works in rep["supporting_works"].items():
        lines += ["", f"## Recent works of {aid}"] + [f"- ({w['year']}) {w['title']} - {w['url']}" for w in works]
    lines += ["", "## Trial evidence"]
    lines += ([f"- {t['nct_id']} via {t['method']} (confidence {t['confidence']:.2f}, reviewed={t['reviewed']}): {t['evidence_uri']}"
               for t in rep["trial_evidence"]] or ["- none (no identifier-based link before the cutoff)"])
    return "\n".join(lines)
